#!/usr/bin/env node
// Compiles prompts/<id>.md into src/prompts.generated.ts so containers never read prompt files at run time.
// A prompt body is its file minus one trailing newline; {{name}} placeholders are lower_snake_case.
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const PLACEHOLDER = /\{\{([a-z][a-z0-9_]*)\}\}/g;
const sha12 = text => createHash("sha256").update(text).digest("hex").slice(0, 12);

export function generatePromptsModule(promptsDir) {
  const ids = readdirSync(promptsDir).filter(name => name.endsWith(".md")).map(name => name.slice(0, -3)).sort();
  if (!ids.length) throw new Error(`No prompts in ${promptsDir}`);
  const entries = ids.map(id => {
    if (!/^[a-z][a-z0-9-]*$/.test(id)) throw new Error(`Prompt id ${id} must be lower-kebab-case`);
    const raw = readFileSync(path.join(promptsDir, `${id}.md`), "utf8");
    const body = raw.endsWith("\n") ? raw.slice(0, -1) : raw;
    const stray = body.replace(PLACEHOLDER, "");
    if (stray.includes("{{") || stray.includes("}}")) throw new Error(`Prompt ${id} has a malformed placeholder`);
    const vars = [...new Set([...body.matchAll(PLACEHOLDER)].map(match => match[1]))].sort();
    return { id, body, vars, hash: sha12(body) };
  });
  const version = sha12(entries.map(entry => `${entry.id}@${entry.hash}\n`).join(""));
  const lines = entries.map(({ id, body, vars, hash }) => `  ${JSON.stringify(id)}: { hash: ${JSON.stringify(hash)}, vars: ${JSON.stringify(vars)}, body: ${JSON.stringify(body)} },`);
  return [
    "// Generated by scripts/build-prompts.mjs from prompts/*.md. Do not edit; run `npm run build-prompts`.",
    "export const PROMPTS = {",
    ...lines,
    "} as const;",
    `export const PROMPTS_VERSION = ${JSON.stringify(version)};`,
    "",
  ].join("\n");
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
  writeFileSync(path.join(root, "src/prompts.generated.ts"), generatePromptsModule(path.join(root, "prompts")));
}
